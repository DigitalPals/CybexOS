"""Select exact NixOS systems for the next boot.

GRUB installations keep their selection in GRUB's environment block. Their
generated menu is labelled when the boot loader is installed: every
generation entry carries an identifier derived from its exact system, so a
selection never follows a regenerated title, position or the floating
current-system entry. Secure Boot installations use Lanzaboote, selected
through systemd-boot's Type 1/UKI interface.
"""
import argparse
import os
from pathlib import Path
import re
import shlex
import subprocess
import tempfile

from .common import Failure, parse, read, syncdir

CONFIG = Path('/etc/cybexos/boot.json')
BRAND = 'Cybex OS'
GENERATIONS = 'cybexos-generations'
CURRENT = 'cybexos-current'
ADDITIONS = '# Cybex OS additions, regenerated with this menu.\n'
SYSTEM = re.compile(r'/nix/store/([a-z0-9]{32})-[^/]+')
SAFE = re.compile(r'cybexos-[a-z]+(-[a-z0-9]{32})?')
OPENING = re.compile(r'''^(\s*)(menuentry|submenu)\s+("(?:[^"\\]|\\.)*"|'[^']*')(.*?)\s*\{\s*$''')
IDENTIFIER = re.compile(r'''\s--id(?:\s+|=)("(?:[^"\\]|\\.)*"|'[^']*'|\S+)''')
SIGNATURE = b'# GRUB Environment Block\n'
WARNING = b'# WARNING: Do not edit this file by tools other than grub-editenv!!!\n'


def entry(system, entries):
    if not SYSTEM.fullmatch(system):
        raise Failure('Invalid retained system identity')
    if not isinstance(entries, list):
        raise Failure('Invalid systemd-boot entry list')
    # bootctl reads both .conf entries and the embedded .cmdline of UKIs. Do
    # not infer a system from a generation number, filename or substring: a
    # specialisation or an unrelated option can contain another system path.
    for candidate in entries:
        if not isinstance(candidate, dict) or candidate.get('type') not in ('type1', 'type2'):
            continue
        options = candidate.get('options', '')
        if not isinstance(options, str):
            continue
        try:
            initializers = [s for s in shlex.split(options) if s.startswith('init=')]
        except ValueError:
            continue
        if initializers != ['init=' + system + '/init']:
            continue
        identifier = candidate.get('id', '')
        if not isinstance(identifier, str) or not re.fullmatch(r'[A-Za-z0-9_.+@-]+\.(conf|efi)', identifier):
            raise Failure('Unsafe systemd-boot entry identity')
        if candidate.get('triesLeft') == 0:
            continue
        # The list is already ordered by systemd's own boot-entry ordering.
        return identifier
    raise Failure('No bootable systemd-boot entry for the retained system; check the ESP and retained generations')


def started(command):
    """The exact system a GRUB linux command starts, or None."""
    try:
        words = shlex.split(command)
    except ValueError:
        return None
    initializers = [word for word in words if word.startswith('init=')]
    if words[:1] != ['linux'] or len(initializers) != 1 or not initializers[0].endswith('/init'):
        return None
    system = initializers[0][len('init='):-len('/init')]
    return system if SYSTEM.fullmatch(system) else None


def unquote(title):
    return title[1:-1] if title[0] == "'" else re.sub(r'\\(.)', r'\1', title[1:-1])


def identifier(node):
    found = IDENTIFIER.findall(node.get('options', ''))
    if not found:
        return None
    return unquote(found[-1]) if found[-1][0] in '\'"' else found[-1]


def menu(text):
    """Parse the menu entries and submenus of a generated GRUB configuration."""
    root = {'kind': 'root', 'children': []}
    stack = [root]
    for number, line in enumerate(text.splitlines()):
        stripped = line.strip()
        if stripped.startswith('#'):
            continue
        opening = OPENING.match(line)
        if opening:
            node = {'kind': opening[2], 'title': unquote(opening[3]), 'options': opening[4],
                    'line': number, 'children': [], 'systems': []}
            next(n for n in reversed(stack) if n['kind'] in ('root', 'submenu'))['children'].append(node)
            stack.append(node)
        elif stripped == '}':
            if len(stack) == 1:
                raise Failure('Unbalanced GRUB menu; boot selection was not changed')
            stack.pop()
        elif stripped.endswith('{'):
            stack.append({'kind': 'block'})
        elif stack[-1]['kind'] == 'menuentry' and stripped.split(None, 1)[:1] == ['linux']:
            stack[-1]['systems'].append(started(stripped))
    if len(stack) != 1:
        raise Failure('Unbalanced GRUB menu; boot selection was not changed')
    for node in walk(root):
        systems = node.get('systems', [])
        node['system'] = systems[0] if len(systems) == 1 else None
    return root


def walk(node):
    for child in node['children']:
        yield child
        if child['kind'] == 'submenu':
            yield from walk(child)


def store_hash(system):
    return SYSTEM.fullmatch(system)[1]


def label(text, distro, closing=''):
    """Brand the menu and identify each generation by its exact system.

    Entries within the generations submenu receive cybexos-system-<hash>;
    a generation with specialisations is a nested submenu named after its
    default system. Equal identifiers boot the same system, so GRUB's first
    match is always the requested one. The top-level entry follows the newest
    generation, so it is never selected by identity. A tail generated with it
    highlights that entry, rather than its submenu, when it is the selection.
    """
    text = text.split(ADDITIONS, 1)[0]
    root = menu(text)
    titles = (distro + ' - All configurations', BRAND + ' - All configurations')
    generations = [n for n in root['children'] if n['kind'] == 'submenu' and n['title'] in titles]
    if len(generations) != 1:
        raise Failure('The generated GRUB menu has no unique system generations submenu')
    identifiers = {generations[0]['line']: GENERATIONS}
    for node in walk(generations[0]):
        if node['kind'] == 'menuentry' and node['system']:
            identifiers[node['line']] = 'cybexos-system-' + store_hash(node['system'])
        elif node['kind'] == 'submenu':
            first = next((n['system'] for n in walk(node) if n['kind'] == 'menuentry' and n['system']), None)
            if first:
                identifiers[node['line']] = 'cybexos-group-' + store_hash(first)
    if not any(value.startswith('cybexos-system-') for value in identifiers.values()):
        raise Failure('The generated GRUB menu lists no bootable system generation')
    tail = ADDITIONS + closing + ('' if not closing or closing.endswith('\n') else '\n')
    # Without specialisations the newest system is one top-level entry.
    current = [n for n in root['children'] if n['kind'] == 'menuentry' and n['system']]
    if len(current) == 1:
        identifiers[current[0]['line']] = CURRENT
        selected = GENERATIONS + '>cybexos-system-' + store_hash(current[0]['system'])
        tail += f'if [ "${{default}}" = "{selected}" ]; then\n  set default={CURRENT}\nfi\n'
    lines = text.splitlines(keepends=True)
    for number, line in enumerate(lines):
        opening = OPENING.match(line.rstrip('\r\n'))
        if not opening:
            continue
        title, options = opening[3], IDENTIFIER.sub('', opening[4])
        rest = title[1 + len(distro):]
        if title[1:].startswith(distro) and rest[:1] in (title[0], ' '):
            title = title[0] + BRAND + rest
        if number in identifiers:
            options += ' --id ' + identifiers[number]
        lines[number] = f'{opening[1]}{opening[2]} {title}{options} {{\n'
    labelled = ''.join(lines)
    return labelled + ('' if labelled.endswith('\n') else '\n') + tail


def grub_entry(system, text):
    """GRUB's identifier path for the first generation entry of a system."""
    if not SYSTEM.fullmatch(system):
        raise Failure('Invalid retained system identity')
    generations = [n for n in menu(text)['children'] if n['kind'] == 'submenu' and identifier(n) == GENERATIONS]
    if len(generations) != 1:
        raise Failure('The GRUB menu has no labelled system generations; reinstall the boot loader')

    def search(node, path):
        for child in node['children']:
            name = identifier(child)
            if child['kind'] == 'menuentry' and child['system'] == system:
                if name != 'cybexos-system-' + store_hash(system):
                    raise Failure('Unsafe GRUB entry identity')
                return path + [name]
            if child['kind'] == 'submenu' and name and SAFE.fullmatch(name):
                found = search(child, path + [name])
                if found:
                    return found
        return None

    found = search(generations[0], [GENERATIONS])
    if not found:
        raise Failure('No bootable GRUB entry for the retained system; check the ESP and retained generations')
    return '>'.join(found)


def parse_environment(data):
    """Read GRUB's environment block exactly as GRUB's envblk parser does.

    Returns its variables and complete comment lines; '#' padding fills the rest.
    """
    broken = Failure('Invalid GRUB environment block; boot selection was not changed')
    if not data.startswith(SIGNATURE):
        raise broken
    values, comments, position, end = {}, [], len(SIGNATURE), len(data)
    while position < end:
        if data[position:position + 1] == b'#':
            newline = data.find(b'\n', position)
            if newline >= 0:
                comments.append(data[position:newline + 1])
            position = end if newline < 0 else newline + 1
            continue
        separator = data.find(b'=', position)
        if separator < 0:
            raise broken
        name, value, position = data[position:separator], bytearray(), separator + 1
        while position < end and data[position:position + 1] != b'\n':
            if data[position:position + 1] == b'\\':
                position += 1
            value += data[position:position + 1]
            position += 1
        if position >= end:
            raise broken
        values[name.decode()] = value.decode()
        position += 1
    return values, comments


def load_environment(data):
    return parse_environment(data)[0]


def dump_environment(values, size=1024, comments=(WARNING,)):
    block = SIGNATURE + b''.join(comments) + b''.join(
        name.encode() + b'=' + value.encode().replace(b'\\', b'\\\\').replace(b'\n', b'\\\n') + b'\n'
        for name, value in values.items())
    if len(block) > size:
        raise Failure('The GRUB environment block is full; boot selection was not changed')
    # GRUB rewrites this block in place at boot; keep its allocated size.
    return block + b'#' * (size - len(block))


def replace(path, data, check=None):
    """Atomically replace a file on the ESP, whose FAT modes are fixed by mount options."""
    path = Path(path)
    descriptor, temporary = tempfile.mkstemp(prefix='.cybexos-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        if check:
            check(temporary)
        os.replace(temporary, path)
        syncdir(path.parent)
    finally:
        Path(temporary).unlink(missing_ok=True)


def grub_trial(arguments, settings):
    environment = Path(settings['environment'])
    try:
        data = environment.read_bytes()
    except FileNotFoundError:
        data = None
    values, comments = parse_environment(data) if data is not None else ({}, [WARNING])
    if arguments == ['--disarm']:
        values.pop('next_entry', None)
    else:
        action, system = arguments
        text = Path(settings['menu']).read_text(encoding='utf-8')
        if action in ('--restore', '--commit'):
            selected = grub_entry(system, text)
            if action == '--restore':
                values.pop('next_entry', None)
            values['saved_entry'] = selected
        else:
            # Resolve both before changing the block. A missing candidate
            # must not alter the persistent default or arm a trial selection.
            candidate, previous = grub_entry(action, text), grub_entry(system, text)
            values['saved_entry'] = previous
            values['next_entry'] = candidate
    replace(environment, dump_environment(values, len(data) if data is not None else 1024, comments))


def systemd_trial(arguments, run):
    if arguments == ['--disarm']:
        run(['bootctl', 'set-oneshot', ''], text=True)
        return
    entries = parse(run(['bootctl', 'list', '--json=short', '--no-pager'], text=True))
    action, system = arguments
    if action in ('--restore', '--commit'):
        selected = entry(system, entries)
        if action == '--restore':
            run(['bootctl', 'set-oneshot', ''], text=True)
        run(['bootctl', 'set-default', selected], text=True)
    else:
        # Resolve both before changing firmware state. A missing candidate
        # must not alter the persistent default or consume a trial selection.
        candidate, previous = entry(action, entries), entry(system, entries)
        run(['bootctl', 'set-default', previous], text=True)
        run(['bootctl', 'set-oneshot', candidate], text=True)


def trial(arguments, run=None, settings=None):
    run = run or subprocess.check_output
    if arguments != ['--disarm'] and (len(arguments) != 2 or arguments[1].startswith('-') or (
            arguments[0].startswith('-') and arguments[0] not in ('--restore', '--commit'))):
        raise Failure('Expected candidate/previous systems, --restore/--commit and a system, or --disarm')
    settings = read(CONFIG) if settings is None else settings
    loader = settings.get('loader') if isinstance(settings, dict) else None
    if loader == 'grub' and all(isinstance(settings.get(key), str) for key in ('menu', 'environment')):
        grub_trial(arguments, settings)
    elif loader == 'systemd-boot':
        systemd_trial(arguments, run)
    else:
        raise Failure('This system has no supported boot selection configuration')


def label_menu(arguments):
    parser = argparse.ArgumentParser(prog='cybexos-boot-menu', description='Label a generated GRUB menu for exact boot selection')
    parser.add_argument('--distro', required=True, help='Distribution name in the generated entry titles')
    parser.add_argument('--append', type=Path, help='Menu entries to add after the generations')
    parser.add_argument('--check', type=Path, required=True, help='grub-script-check executable')
    parser.add_argument('menu', type=Path)
    options = parser.parse_args(arguments)
    closing = options.append.read_text(encoding='utf-8') if options.append else ''
    labelled = label(options.menu.read_text(encoding='utf-8'), options.distro, closing)

    def check(path):
        result = subprocess.run([str(options.check), path], capture_output=True, text=True)
        if result.returncode:
            raise Failure('Labelled GRUB menu failed its syntax check: ' + (result.stdout + result.stderr).strip()[-2000:])

    replace(options.menu, labelled.encode(), check)
