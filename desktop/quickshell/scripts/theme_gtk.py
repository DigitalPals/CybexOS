"""System theme target: GTK and libadwaita, through org.gnome.desktop.interface.

GTK 3 follows `gtk-theme` (the adw-gtk3 pair, so GTK 3 applications match
libadwaita ones), libadwaita follows `color-scheme` and `accent-color`, and
applications that ask the settings portal (Firefox, Chromium, Electron) read
the same keys through xdg-desktop-portal-gtk. `text-scaling-factor` sizes
their text with the shell's. All of them pick a change up while running.

gsettings holds the state, so the rendered gtk.json only records what was last
applied: an unchanged record is how the driver knows no call is needed.

The text scale is the one key people also set elsewhere (GNOME Tweaks, an
accessibility guide), so it is set only while it still holds the value this
target set last, or GNOME's default. A value of the user's own wins, as
user.lua does over the compositor colours, until
`gsettings reset org.gnome.desktop.interface text-scaling-factor` hands the
key back; `theme apply` does not override it either.

The desktop style reaches GTK too. The Mac-like style moves the window
buttons to the left (`button-layout`, which libadwaita, GTK 3 and Chromium
follow through the settings portal), sets the interface font to Inter, and
renders gtk-3.0.css and gtk-4.0.css: traffic-light window buttons and sidebar
icons in the accent. Those stylesheets reach applications through an
`@import` that cybexos-personal-init seeds in ~/.config/gtk-{3,4}.0/gtk.css
when that file does not exist yet; GTK reads them when an application starts.
The two keys follow the text scale's rule: they are changed only while they
hold GNOME's default or the value this target set last (recorded in
gtk-style.json), and the Cybex style hands back to GNOME's default only a key
this target set and nobody has changed since.
"""
import colorsys
import json
import os
import shutil
import subprocess
import tempfile

import theme_tokens

NAME = 'gtk'
SCHEMA = 'org.gnome.desktop.interface'
TIMEOUT = 10
TEXT_SCALE_KEY = 'text-scaling-factor'
# What reload() last set the text scale to; not a rendered file, so writing
# it never counts as a change.
APPLIED_FILE = 'gtk-text-scale'

GTK_THEMES = {'dark': 'adw-gtk3-dark', 'light': 'adw-gtk3'}

WM_SCHEMA = 'org.gnome.desktop.wm.preferences'
# (schema, key, GNOME's defaults, the Mac-like style's value). GNOME 48
# replaced Cantarell with Adwaita Sans as the default interface font.
STYLE_KEYS = (
    (WM_SCHEMA, 'button-layout', ('appmenu:close',), 'close,minimize,maximize:'),
    (SCHEMA, 'font-name', ('Adwaita Sans 11', 'Cantarell 11'), 'Inter 11'),
)
# The traffic lights and, out of focus, the grey every button turns.
LIGHTS = {'close': ('#ff5f57', '#4d0000'), 'minimize': ('#febc2e', '#985700'),
          'maximize': ('#28c840', '#006500')}
BACKDROP = {'dark': '#4b4b4f', 'light': '#d2d2d5'}
# The style keys reload() set last, {"schema key": value}; like APPLIED_FILE,
# a record rather than a rendered file.
STYLE_APPLIED_FILE = 'gtk-style.json'

# libadwaita's named accents (GNOME 47) by the hue of the colour it draws for
# each. Slate is the grey-blue one: it takes accents with too little colour to
# have a meaningful hue.
ACCENT_HUES = (
    ('blue', theme_tokens.rgb('#3584e4')),
    ('teal', theme_tokens.rgb('#2190a4')),
    ('green', theme_tokens.rgb('#3a944a')),
    ('yellow', theme_tokens.rgb('#c88800')),
    ('orange', theme_tokens.rgb('#ed5b00')),
    ('red', theme_tokens.rgb('#e62d42')),
    ('pink', theme_tokens.rgb('#d56199')),
    ('purple', theme_tokens.rgb('#9141ac')),
)
# Chroma (max - min channel) below which an accent reads as grey. libadwaita's
# own slate, #6f8396, sits just under it.
SLATE_CHROMA = 0.16


def _hue(channels):
    return colorsys.rgb_to_hsv(*channels)[0] * 360


def accent_name(value):
    """The libadwaita accent nearest to a "#rrggbb" colour by hue."""
    channels = theme_tokens.rgb(value)
    if max(channels) - min(channels) < SLATE_CHROMA:
        return 'slate'
    hue = _hue(channels)

    def distance(entry):
        gap = abs(hue - _hue(entry[1])) % 360
        return min(gap, 360 - gap)
    return min(ACCENT_HUES, key=distance)[0]


def text_scaling_factor(tokens):
    """GNOME's text-scaling-factor: 1.00 at the shell's default text size."""
    return f'{theme_tokens.text_scale(tokens):.2f}'


def settings(tokens):
    """The org.gnome.desktop.interface values for tokens, in the order they are set."""
    mode = tokens['mode']
    return {
        'color-scheme': f'prefer-{mode}',
        'gtk-theme': GTK_THEMES[mode],
        'accent-color': accent_name(tokens['colors']['accent']),
        TEXT_SCALE_KEY: text_scaling_factor(tokens),
    }


def style_settings(tokens):
    """{(schema, key): value} the desktop style asks for; None is GNOME's default."""
    mac = tokens['style'] == 'mac'
    return {(schema, key): (value if mac else None) for schema, key, _defaults, value in STYLE_KEYS}


CSS_HEADER = """\
/* Generated by Cybex OS from the desktop style (theme-apply.py). Every
 * appearance change replaces this file; put rules of your own in gtk.css,
 * below its @import line. */
"""


def stylesheet(tokens, version):
    """gtk-3.0.css or gtk-4.0.css: Mac-like window buttons, or nothing."""
    if tokens['style'] != 'mac':
        return CSS_HEADER
    backdrop = BACKDROP[tokens['mode']]
    if version == 4:
        # libadwaita draws a window button's circle on its image.
        button, face, hover = 'windowcontrols > button', 'windowcontrols > button.{name} > image', \
            'windowcontrols:hover > button.{name} > image'
        rules = [
            'windowcontrols { border-spacing: 8px; }',
            f'{button} {{ min-width: 14px; min-height: 14px; padding: 0; margin: 0; '
            'background: none; box-shadow: none; }',
            f'{button} > image {{ min-width: 12px; min-height: 12px; padding: 0; border-radius: 100%; '
            '-gtk-icon-size: 8px; color: transparent; box-shadow: inset 0 0 0 1px rgba(0, 0, 0, 0.12); }',
            f'window:backdrop {button} > image {{ background-color: {backdrop}; }}',
            '.navigation-sidebar row image { color: @accent_color; }',
        ]
        backdrop_face = 'window:backdrop windowcontrols:hover > button.{name} > image'
    else:
        button = 'headerbar button.titlebutton, .titlebar button.titlebutton'
        face = 'button.titlebutton.{name}'
        hover = 'button.titlebutton.{name}:hover'
        rules = [
            f'{button} {{ min-width: 12px; min-height: 12px; padding: 0; margin: 0 4px; '
            'border: none; border-radius: 100%; background-image: none; color: transparent; '
            'box-shadow: inset 0 0 0 1px rgba(0, 0, 0, 0.12); -gtk-icon-shadow: none; }',
            'button.titlebutton image { -gtk-icon-transform: scale(0.6); }',
            f'headerbar:backdrop button.titlebutton, .titlebar:backdrop button.titlebutton '
            f'{{ background-color: {backdrop}; }}',
            'placessidebar row image { color: @accent_color; }',
        ]
        backdrop_face = 'headerbar:backdrop button.titlebutton.{name}:hover'
    for name, (fill, ink) in LIGHTS.items():
        rules.append(f'{face.format(name=name)} {{ background-color: {fill}; }}')
        rules.append(f'{hover.format(name=name)}, {backdrop_face.format(name=name)} '
                     f'{{ background-color: {fill}; color: {ink}; }}')
    return CSS_HEADER + '\n'.join(rules) + '\n'


def render(tokens):
    record = dict(settings(tokens))
    record.update({f'{schema} {key}': value
                   for (schema, key), value in style_settings(tokens).items()})
    return {'gtk.json': json.dumps(record, indent=2, sort_keys=True) + '\n',
            'gtk-3.0.css': stylesheet(tokens, 3), 'gtk-4.0.css': stylesheet(tokens, 4)}


def _gsettings(action, *args, schema=SCHEMA):
    """Runs `gsettings action SCHEMA args...` and returns its output."""
    what = ' '.join(('gsettings', action, *args[:1]))  # the key, never the value
    try:
        result = subprocess.run(['gsettings', action, schema, *args], stdin=subprocess.DEVNULL,
                                capture_output=True, text=True, timeout=TIMEOUT, check=False)
    except subprocess.TimeoutExpired:
        raise RuntimeError(f'{what} timed out') from None
    if result.returncode != 0:
        lines = (result.stderr or result.stdout).strip().splitlines()
        detail = lines[0] if lines else f'exit status {result.returncode}'
        raise RuntimeError(f'{what} failed: {detail}')
    return result.stdout


def _number(text):
    try:
        return float(text)
    except (TypeError, ValueError):
        return None


def _read_applied(directory):
    try:
        with open(os.path.join(directory, APPLIED_FILE), encoding='utf-8') as handle:
            return _number(handle.read(64).strip())
    except OSError:
        return None


def _write_applied(directory, value):
    descriptor, temporary = tempfile.mkstemp(dir=directory, prefix=f'.{APPLIED_FILE}.')
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8') as handle:
            handle.write(value + '\n')
        os.chmod(temporary, 0o644)
        os.replace(temporary, os.path.join(directory, APPLIED_FILE))
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def owns_text_scale(current, applied):
    """Whether the key still holds a value the shell may replace.

    GNOME's default (1.0) and the value this target set last are the shell's;
    anything else was set by someone else and is left alone.
    """
    value = _number(current)
    return value is None or any(abs(value - mine) < 0.005
                                for mine in (1.0, applied) if mine is not None)


def _string(text):
    """A gsettings string value without its GVariant quotes."""
    text = (text or '').strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in '\'"':
        return text[1:-1]
    return text


def _read_style_applied(directory):
    try:
        with open(os.path.join(directory, STYLE_APPLIED_FILE), encoding='utf-8') as handle:
            record = json.loads(handle.read(4096))
    except (OSError, ValueError):
        return {}
    return {name: value for name, value in record.items() if isinstance(value, str)} \
        if isinstance(record, dict) else {}


def _write_style_applied(directory, record):
    descriptor, temporary = tempfile.mkstemp(dir=directory, prefix=f'.{STYLE_APPLIED_FILE}.')
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8') as handle:
            handle.write(json.dumps(record, sort_keys=True) + '\n')
        os.chmod(temporary, 0o644)
        os.replace(temporary, os.path.join(directory, STYLE_APPLIED_FILE))
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def apply_style(tokens, interface_keys, directory):
    """Sets or hands back the style's keys, touching only what is the shell's:
    a key holding GNOME's default, or the value this target set last."""
    wanted = style_settings(tokens)
    applied = _read_style_applied(directory)
    record = dict(applied)
    known = {SCHEMA: interface_keys}
    for schema, key, defaults, _mine in STYLE_KEYS:
        if schema not in known:
            known[schema] = set(_gsettings('list-keys', schema=schema).split())
        if key not in known[schema]:
            continue
        name = f'{schema} {key}'
        current = _string(_gsettings('get', key, schema=schema))
        value = wanted[(schema, key)]
        ours = applied.get(name)
        if value is None:
            if ours is not None and current == ours:
                _gsettings('reset', key, schema=schema)
            record.pop(name, None)
        elif current in defaults or current == ours:
            if current != value:
                _gsettings('set', key, value, schema=schema)
            record[name] = value
        else:
            record.pop(name, None)
    if record != applied:
        _write_style_applied(directory, record)


def reload(tokens, directory):
    if shutil.which('gsettings') is None:
        # glib2 ships gsettings on every Cybex OS install, so a PATH without it
        # is a bare environment (the driver tests run with an empty one), not
        # a desktop with GTK applications to follow it.
        return
    # accent-color arrived with GNOME 47; an older schema simply lacks the key
    # and libadwaita keeps its default blue.
    keys = set(_gsettings('list-keys').split())
    for key, value in settings(tokens).items():
        if key == TEXT_SCALE_KEY:
            if key not in keys or not owns_text_scale(
                    _gsettings('get', key).strip(), _read_applied(directory)):
                continue
            _gsettings('set', key, value)
            _write_applied(directory, value)
        elif key != 'accent-color' or key in keys:
            _gsettings('set', key, value)
    apply_style(tokens, keys, directory)
