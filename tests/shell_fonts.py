"""The installed desktop's fonts for the real-engine shell checks.

The host running a check has its own fontconfig, which usually lacks the
shell's faces. Qt then substitutes whatever the host offers (on Debian,
Nimbus Sans, whose medium and bold faces Qt draws oblique), and screenshots
stop showing what an installation shows. `fontconfig()` builds the default
desktop's own `/etc/fonts`: the payload system's `environment.etc.fonts`,
generated by NixOS from `fonts.packages` (nix/modules/applications.nix) and
its defaults, with their conf.d rules. It returns a private FONTCONFIG_FILE
that reads that tree instead of the host's /etc/fonts.

CYBEXOS_TEST_FONTS_ETC may name an already built `.../etc/fonts` directory.
"""
from __future__ import annotations
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
NIX = ['nix', '--extra-experimental-features', 'nix-command flakes']
ATTRIBUTE = '.#nixosConfigurations.installer.config.cybexos.installer.payload.config.environment.etc.fonts.source'


def installed_fonts_etc() -> Path:
    configured = os.environ.get('CYBEXOS_TEST_FONTS_ETC')
    if configured:
        return Path(configured)
    # The option's value is "<out>/etc/fonts/"; build its derivation.
    drv = subprocess.run(NIX + ['eval', '--raw', ATTRIBUTE, '--apply',
                                's: builtins.head (builtins.attrNames (builtins.getContext s))'],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    out = subprocess.run(NIX + ['build', '--no-link', '--print-out-paths', drv + '^out'],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    return Path(out) / 'etc/fonts'


def fontconfig(directory: Path) -> dict:
    """Write DIRECTORY/fonts.conf and return the environment that selects it."""
    etc = installed_fonts_etc()
    source = (etc / 'fonts.conf').read_text()
    host_rules = '<include ignore_missing="yes">/etc/fonts/conf.d</include>'
    assert source.count(host_rules) == 1, 'unexpected fonts.conf layout'
    cache = directory / 'fontconfig-cache'
    cache.mkdir(parents=True, exist_ok=True)
    lines = [line for line in source.replace(host_rules, f'<include>{etc}/conf.d</include>').splitlines()
             if '<cachedir' not in line]
    lines.insert(lines.index('</fontconfig>'), f'<cachedir>{cache}</cachedir>')
    target = directory / 'fonts.conf'
    target.write_text('\n'.join(lines) + '\n')
    return {'FONTCONFIG_FILE': str(target)}
