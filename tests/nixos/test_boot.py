from cybexos.common import Failure

OLD = '/nix/store/' + 'a' * 32 + '-nixos-system-old'
NEW = '/nix/store/' + 'b' * 32 + '-nixos-system-new'
RESCUE = '/nix/store/' + 'c' * 32 + '-nixos-system-rescue'
SYSTEMD = {'loader': 'systemd-boot'}
CLOSING = "menuentry 'Firmware settings' --class firmware {\n  fwsetup\n}\n"
VERSIONS = {NEW: '1.0.0-beta.19', OLD: '1.0.0-beta.18', RESCUE: '1.0.0-beta.18'}
THEME = {f'{kind}-{rows}' for kind in ('startup', 'notice', 'earlier') for rows in range(1, 7)}


class FakeSystems(Systems):
    """Versions from release.json and generation times from profile links."""

    def __init__(self, missing=(), now=datetime(2026, 10, 29, 9)):
        super().__init__('/nonexistent', now)
        self.missing = missing

    def version(self, system):
        return VERSIONS.get(system)

    def created(self, generation):
        return None if int(generation) in self.missing else datetime(2026, 10, 20 + int(generation), 14, 5)


def boot_entry(system, identifier, kind='type1'):
    return {'id': identifier, 'type': kind, 'options': 'quiet init=' + system + '/init loglevel=4'}


def grub_body(system):
    return ('search --set=drive1 --fs-uuid 1234-ABCD\n'
            '  linux ($drive1)//kernels/' + 'k' * 32 + '-linux-7.2-bzImage init=' + system
            + '/init quiet udev.log_level=3 loglevel=3 splash\n'
            '  initrd ($drive1)//kernels/' + 'i' * 32 + '-initrd-linux-7.2-initrd\n}\n\n')


def generated(current=NEW, generations=((2, NEW), (1, OLD)), specialised=None):
    """The shape of NixOS install-grub.pl output with a theme and no savedefault."""
    text = '''# Automatically generated.  DO NOT EDIT THIS FILE!

    search --set=drive1 --fs-uuid 1234-ABCD
    if [ -s $prefix/grubenv ]; then
      load_env
    fi

    # ‘grub-reboot’ sets a one-time saved entry, which we process here and
    # then delete.
    if [ "${next_entry}" ]; then
      set default="${next_entry}"
      set next_entry=
      save_env next_entry
      set timeout=1
      set boot_once=true
    else
      set default="${saved_entry}"
      set timeout=5
    fi
    set timeout_style=menu

    function savedefault {
        if [ -z "${boot_once}"]; then
        saved_entry="${chosen}"
        save_env saved_entry
        fi
    }

        # Sets theme.
        set theme=($drive1)//theme/theme.txt
        export theme

menuentry "NixOS" --class nixos --unrestricted {
''' + grub_body(current) + '\nsubmenu "NixOS - All configurations" --class submenu {\n'
    for number, system in generations:
        suffix = f' (2026-10-2{number} - 26.05.20261020.da6dc0e)'
        if number == specialised:
            text += f'submenu "NixOS - Configuration {number}{suffix}" --class submenu {{\n'
            text += f'menuentry "NixOS - Configuration {number} - Default{suffix}" --class nixos {{\n' + grub_body(system)
            text += f'menuentry "NixOS - Configuration {number} - (rescue - 2026-10-2{number} - 26.05)"  {{\n' + grub_body(RESCUE)
            text += '}\n'
        else:
            text += f'menuentry "NixOS - Configuration {number}{suffix}" --class nixos {{\n' + grub_body(system)
    return text + '}\n'


class BootSelectionTests(unittest.TestCase):
    def test_standard_entries_and_lanzaboote_ukis(self):
        for kind, suffix in [('type1', 'conf'), ('type2', 'efi')]:
            entries = [boot_entry(NEW, 'nixos-generation-2.' + suffix, kind),
                       boot_entry(OLD, 'nixos-generation-1.' + suffix, kind)]
            calls = []
            def run(args, **kwargs):
                calls.append(args)
                return json.dumps(entries) if args[1] == 'list' else ''
            trial([NEW, OLD], run, SYSTEMD)
            self.assertEqual(calls[1:], [['bootctl', 'set-default', 'nixos-generation-1.' + suffix],
                                        ['bootctl', 'set-oneshot', 'nixos-generation-2.' + suffix]])
            calls.clear()
            trial(['--restore', OLD], run, SYSTEMD)
            self.assertEqual(calls[1:], [['bootctl', 'set-oneshot', ''],
                                        ['bootctl', 'set-default', 'nixos-generation-1.' + suffix]])
            calls.clear()
            trial(['--commit', NEW], run, SYSTEMD)
            self.assertEqual(calls[1:], [['bootctl', 'set-default', 'nixos-generation-2.' + suffix]])
            calls.clear()
            trial(['--disarm'], run, SYSTEMD)
            self.assertEqual(calls, [['bootctl', 'set-oneshot', '']])

    def test_no_substring_specialisation_or_ambiguous_init_match(self):
        for options in ['other=' + NEW + ' init=' + OLD + '/init',
                        'init=' + NEW + '/init-other',
                        'init=' + NEW + '/init init=' + OLD + '/init',
                        'init=' + NEW + '/specialisation/rescue/init']:
            with self.subTest(options=options), self.assertRaises(Failure):
                entry(NEW, [{'type': 'type1', 'id': 'nixos-generation-2.conf', 'options': options}])

    def test_missing_candidate_changes_no_firmware_state(self):
        calls = []
        def run(args, **kwargs):
            calls.append(args)
            return json.dumps([boot_entry(OLD, 'nixos-generation-1.conf')])
        with self.assertRaises(Failure):
            trial([NEW, OLD], run, SYSTEMD)
        self.assertEqual(len(calls), 1)

    def test_reject_unsafe_or_exhausted_entries(self):
        with self.assertRaises(Failure):
            entry(NEW, [boot_entry(NEW, '*.efi', 'type2')])
        with self.assertRaises(Failure):
            entry(NEW, [boot_entry(NEW, 'nixos-2.efi', 'type2') | {'triesLeft': 0}])

    def test_unconfigured_or_malformed_requests_change_nothing(self):
        def run(args, **kwargs):
            raise AssertionError('No boot command may run')
        for settings in [None, {}, {'loader': 'grub'}, {'loader': 'refind'}]:
            with self.subTest(settings=settings), self.assertRaises(Failure):
                trial(['--disarm'], run, settings or {})
        for arguments in ([NEW], ['--disarm', NEW], ['--restore', '--commit'], ['--unknown', NEW], [NEW, OLD, OLD]):
            with self.subTest(arguments=arguments), self.assertRaises(Failure):
                trial(arguments, run, SYSTEMD)


class GrubMenuTests(unittest.TestCase):
    def test_label_brands_titles_and_identifies_exact_systems(self):
        labelled = label(generated(), 'NixOS', CLOSING, systems=FakeSystems())
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.19' --class cybexos --class nixos --unrestricted --id cybexos-current {\n",
                      labelled)
        self.assertIn("submenu 'Earlier versions  ›' --class history --class submenu --id cybexos-generations {\n", labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.19  ·  22 Oct, 14:05' --class cybexos --class nixos"
                      ' --id cybexos-system-' + 'b' * 32 + ' {\n', labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05' --class history --class nixos"
                      ' --id cybexos-system-' + 'a' * 32 + ' {\n', labelled)
        self.assertNotIn('NixOS', ''.join(line for line in labelled.splitlines() if 'menuentry' in line or 'submenu' in line))
        # The floating entry is highlighted only when it is the exact selection.
        # A start GRUB marked but the system never confirmed opens the menu.
        self.assertTrue(labelled.endswith('}\n# Cybex OS additions, regenerated with this menu.\n' + CLOSING
                                          + 'if [ "${default}" = "cybexos-generations>cybexos-system-' + 'b' * 32 + '" ]; then\n'
                                          '  set default=cybexos-current\nfi\n'
                                          'if [ "${cybexos_boot}" = "pending" ]; then\n'
                                          '  set timeout_style=menu\n  set timeout=30\nfi\n'))
        # Everything other than the opening lines is unchanged.
        self.assertEqual(len(labelled.splitlines()), len(generated().splitlines()) + 1 + len(CLOSING.splitlines()) + 3 + 4)
        self.assertIn('‘grub-reboot’', labelled)
        # Labelling again, as after an interrupted installation, is stable.
        self.assertEqual(label(labelled, 'NixOS', CLOSING, systems=FakeSystems()), labelled)

    def test_theme_variants_follow_each_list_length(self):
        labelled = label(generated(specialised=1), 'NixOS', CLOSING, THEME.__contains__, FakeSystems())
        lines = labelled.splitlines()
        generations = lines.index("submenu 'Earlier versions  ›' --class history --class submenu --id cybexos-generations {")
        self.assertEqual(lines[generations + 1], '  set theme=($drive1)//theme/earlier-2.txt')
        group = next(i for i, line in enumerate(lines) if line.startswith("submenu 'Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05  ›'"))
        self.assertEqual(lines[group + 1], '  set theme=($drive1)//theme/earlier-2.txt')
        # The current entry, the generations and the closing entry.
        self.assertIn('set theme=($drive1)//theme/startup-3.txt\nif [ "${cybexos_boot}" = "pending" ]; then\n'
                      '  set theme=($drive1)//theme/notice-3.txt\n  set timeout_style=menu\n  set timeout=30\nfi\n', labelled)
        self.assertEqual(label(labelled, 'NixOS', CLOSING, THEME.__contains__, FakeSystems()), labelled)
        many = generated(generations=tuple((n, NEW if n % 2 else OLD) for n in range(9, 0, -1)))
        self.assertIn('  set theme=($drive1)//theme/earlier-6.txt\n', label(many, 'NixOS', '', THEME.__contains__, FakeSystems()))
        # A personal theme without the variants keeps its own theme.txt.
        personal = label(generated(), 'NixOS', CLOSING, lambda name: False, FakeSystems())
        self.assertNotIn('-1.txt', personal)
        self.assertNotIn('/theme/startup-', personal)
        self.assertIn('  set timeout_style=menu\n', personal)
        self.assertNotIn('/theme/', label(generated().replace('        set theme=($drive1)//theme/theme.txt\n', ''),
                                          'NixOS', CLOSING, THEME.__contains__, FakeSystems()))

    def test_titles_without_version_or_profile_time(self):
        labelled = label(generated(), 'NixOS', systems=FakeSystems(missing=(2,), now=datetime(2027, 1, 3)))
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.19  ·  22 Oct 2026' --class cybexos", labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.18  ·  21 Oct 2026, 14:05' --class history", labelled)
        unknown = label(generated(), 'NixOS', systems=Systems('/nonexistent', datetime(2026, 10, 29)))
        self.assertIn("menuentry 'Cybex OS' --class cybexos --class nixos --unrestricted --id cybexos-current {\n", unknown)
        self.assertIn("menuentry 'Cybex OS  ·  22 Oct' --class cybexos --class nixos --id cybexos-system-", unknown)
        quoted = generated(specialised=1).replace('(rescue - 2026-10-21 - 26.05)', "it's $ \\\"odd\\\"")
        self.assertIn('menuentry "Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05  ·  it\'s \\$ \\\"odd\\\"" --class history',
                      label(quoted, 'NixOS', systems=FakeSystems()))

    def test_specialised_current_system_is_never_highlighted_by_identity(self):
        specialised = generated().replace('menuentry "NixOS" --class nixos --unrestricted {\n' + grub_body(NEW),
                                          'menuentry "NixOS - Default" --class nixos --unrestricted {\n' + grub_body(NEW)
                                          + 'menuentry "NixOS - (rescue - 2026-10-22 - 26.05)"  {\n' + grub_body(RESCUE))
        labelled = label(specialised, 'NixOS', systems=FakeSystems())
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.19' --class cybexos --class nixos --unrestricted {\n", labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.18  ·  rescue' --class cybexos {\n", labelled)
        self.assertNotIn('cybexos-current', labelled)
        self.assertEqual(grub_entry(NEW, labelled), 'cybexos-generations>cybexos-system-' + 'b' * 32)

    def test_selection_follows_exact_system_not_title_or_position(self):
        labelled = label(generated(), 'NixOS')
        self.assertEqual(grub_entry(OLD, labelled), 'cybexos-generations>cybexos-system-' + 'a' * 32)
        self.assertEqual(grub_entry(NEW, labelled), 'cybexos-generations>cybexos-system-' + 'b' * 32)
        # A restored previous system is a newer generation with the same system.
        relabelled = label(generated(OLD, ((3, OLD), (2, NEW), (1, OLD))), 'NixOS')
        self.assertEqual(grub_entry(OLD, relabelled), 'cybexos-generations>cybexos-system-' + 'a' * 32)
        with self.assertRaisesRegex(Failure, 'No bootable GRUB entry'):
            grub_entry('/nix/store/' + 'd' * 32 + '-nixos-system-absent', labelled)

    def test_specialised_generation_is_a_nested_identified_submenu(self):
        labelled = label(generated(specialised=1), 'NixOS', systems=FakeSystems())
        self.assertIn("submenu 'Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05  ›' --class history --class submenu"
                      ' --id cybexos-group-' + 'a' * 32 + ' {\n', labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05' --class history --class nixos --id cybexos-system-"
                      + 'a' * 32 + ' {\n', labelled)
        self.assertIn("menuentry 'Cybex OS 1.0.0-beta.18  ·  21 Oct, 14:05  ·  rescue' --class history --id cybexos-system-"
                      + 'c' * 32 + ' {\n', labelled)
        self.assertEqual(grub_entry(OLD, labelled),
                         'cybexos-generations>cybexos-group-' + 'a' * 32 + '>cybexos-system-' + 'a' * 32)
        self.assertEqual(grub_entry(RESCUE, labelled),
                         'cybexos-generations>cybexos-group-' + 'a' * 32 + '>cybexos-system-' + 'c' * 32)

    def test_unlabelled_or_unsafe_menus_select_nothing(self):
        with self.assertRaisesRegex(Failure, 'no labelled system generations'):
            grub_entry(OLD, generated())
        tampered = label(generated(), 'NixOS').replace('--id cybexos-system-' + 'a' * 32, '--id cybexos-system-' + 'b' * 32)
        with self.assertRaisesRegex(Failure, 'Unsafe GRUB entry identity'):
            grub_entry(OLD, tampered)
        for system in ['/nix/store/short-system', OLD + '/specialisation/rescue', 'cybexos-generations']:
            with self.subTest(system=system), self.assertRaises(Failure):
                grub_entry(system, label(generated(), 'NixOS'))

    def test_label_rejects_unexpected_generated_menus(self):
        with self.assertRaisesRegex(Failure, 'no unique system generations'):
            label(generated().replace('All configurations', 'Everything'), 'NixOS')
        with self.assertRaisesRegex(Failure, 'Unbalanced'):
            label(generated() + '}\n', 'NixOS')
        with self.assertRaisesRegex(Failure, 'Unbalanced'):
            label(generated()[:-2], 'NixOS')
        with self.assertRaisesRegex(Failure, 'no bootable system generation'):
            label(generated(generations=()), 'NixOS')

    def test_entries_with_ambiguous_initializers_are_not_identified(self):
        ambiguous = generated().replace('/init quiet', '/init init=' + OLD + '/init quiet', 1)
        root = menu(ambiguous)
        self.assertIsNone(root['children'][0]['system'])
        self.assertEqual([n['system'] for n in root['children'][1]['children']], [NEW, OLD])


class GrubEnvironmentTests(unittest.TestCase):
    def setUp(self):
        self.directory = Path(tempfile.mkdtemp(prefix='cybexos-boot-test-'))
        self.addCleanup(shutil.rmtree, self.directory)
        self.menu = self.directory / 'grub.cfg'
        self.menu.write_text(label(generated(), 'NixOS'), encoding='utf-8')
        self.environment = self.directory / 'grubenv'
        run = Path(tempfile.mkdtemp(prefix='cybexos-boot-run-'))
        self.addCleanup(shutil.rmtree, run)
        self.settings = {'loader': 'grub', 'menu': str(self.menu), 'environment': str(self.environment),
                         'lock': str(run / 'boot.lock')}

    def values(self):
        data = self.environment.read_bytes()
        self.assertEqual(len(data), 1024)
        return load_environment(data)

    def test_encoding_round_trip_and_escapes(self):
        values = {'saved_entry': 'cybexos-generations>cybexos-system-' + 'a' * 32, 'odd': 'back\\slash\nnewline', 'empty': ''}
        block = dump_environment(values)
        self.assertEqual(len(block), 1024)
        self.assertTrue(block.startswith(b'# GRUB Environment Block\n'))
        self.assertTrue(block.endswith(b'#'))
        self.assertEqual(load_environment(block), values)
        with self.assertRaisesRegex(Failure, 'full'):
            dump_environment({'large': 'x' * 1024})
        for broken in [b'not an environment block', b'# GRUB Environment Block\nname', b'# GRUB Environment Block\nname=value']:
            with self.subTest(broken=broken), self.assertRaises(Failure):
                load_environment(broken)

    def test_trial_commit_restore_and_disarm(self):
        old = 'cybexos-generations>cybexos-system-' + 'a' * 32
        new = 'cybexos-generations>cybexos-system-' + 'b' * 32
        self.environment.write_bytes(dump_environment({'unrelated': 'kept'}))
        trial([NEW, OLD], settings=self.settings)
        self.assertEqual(self.values(), {'unrelated': 'kept', 'saved_entry': old, 'next_entry': new})
        # GRUB empties next_entry when it boots the trial.
        self.environment.write_bytes(dump_environment({'unrelated': 'kept', 'saved_entry': old, 'next_entry': ''}))
        trial(['--commit', NEW], settings=self.settings)
        self.assertEqual(self.values(), {'unrelated': 'kept', 'saved_entry': new, 'next_entry': ''})
        trial([NEW, OLD], settings=self.settings)
        trial(['--restore', OLD], settings=self.settings)
        self.assertEqual(self.values(), {'unrelated': 'kept', 'saved_entry': old})
        trial([NEW, OLD], settings=self.settings)
        trial(['--disarm'], settings=self.settings)
        self.assertEqual(self.values(), {'unrelated': 'kept', 'saved_entry': old})
        self.assertEqual(sorted(p.name for p in self.directory.iterdir()), ['grub.cfg', 'grubenv'])

    def test_missing_candidate_or_broken_block_changes_nothing(self):
        before = dump_environment({'saved_entry': 'cybexos-generations>cybexos-system-' + 'a' * 32})
        self.environment.write_bytes(before)
        absent = '/nix/store/' + 'd' * 32 + '-nixos-system-absent'
        for arguments in ([absent, OLD], [NEW, absent], ['--commit', absent], ['--restore', absent]):
            with self.subTest(arguments=arguments), self.assertRaises(Failure):
                trial(arguments, settings=self.settings)
            self.assertEqual(self.environment.read_bytes(), before)
        self.environment.write_bytes(b'corrupt')
        with self.assertRaises(Failure):
            trial(['--disarm'], settings=self.settings)
        self.assertEqual(self.environment.read_bytes(), b'corrupt')

    def test_finished_start_clears_only_its_mark(self):
        kept = {'saved_entry': 'cybexos-generations>cybexos-system-' + 'a' * 32, 'next_entry': ''}
        self.environment.write_bytes(dump_environment({**kept, 'cybexos_boot': 'pending'}))
        self.assertTrue(confirm_start(self.settings))
        self.assertEqual(self.values(), kept)
        before = self.environment.read_bytes()
        self.assertFalse(confirm_start(self.settings))
        self.assertEqual(self.environment.read_bytes(), before)
        for settings in [SYSTEMD, {}, {'loader': 'grub'}]:
            self.assertFalse(confirm_start(settings))
        self.environment.unlink()
        self.assertFalse(confirm_start(self.settings))
        self.assertFalse(self.environment.exists())

    def test_absent_block_is_created_at_grub_size(self):
        trial(['--commit', OLD], settings=self.settings)
        self.assertEqual(self.values(), {'saved_entry': 'cybexos-generations>cybexos-system-' + 'a' * 32})

    @unittest.skipUnless(shutil.which('grub-editenv'), 'GRUB tools are unavailable')
    def test_block_matches_grub_editenv(self):
        values = {'saved_entry': 'cybexos-generations>cybexos-system-' + 'a' * 32, 'next_entry': '', 'odd': 'a\\b'}
        self.environment.write_bytes(dump_environment(values))
        listed = subprocess.run(['grub-editenv', str(self.environment), 'list'], check=True, capture_output=True, text=True).stdout
        self.assertEqual(listed.splitlines(), [name + '=' + value for name, value in values.items()])
        native = self.directory / 'native'
        subprocess.run(['grub-editenv', str(native), 'create'], check=True)
        subprocess.run(['grub-editenv', str(native), 'set', 'next_entry=x>y', 'odd=a\\b'], check=True)
        self.assertEqual(load_environment(native.read_bytes()), {'next_entry': 'x>y', 'odd': 'a\\b'})
        self.assertEqual(native.read_bytes(), dump_environment({'next_entry': 'x>y', 'odd': 'a\\b'}))
        # A trial on a block from grub-install equals GRUB's own encoding.
        old = 'cybexos-generations>cybexos-system-' + 'a' * 32
        new = 'cybexos-generations>cybexos-system-' + 'b' * 32
        self.environment.unlink()
        subprocess.run(['grub-editenv', str(self.environment), 'create'], check=True)
        trial([NEW, OLD], settings=self.settings)
        native.unlink()
        subprocess.run(['grub-editenv', str(native), 'create'], check=True)
        subprocess.run(['grub-editenv', str(native), 'set', 'saved_entry=' + old, 'next_entry=' + new], check=True)
        self.assertEqual(self.environment.read_bytes(), native.read_bytes())

    @unittest.skipUnless(shutil.which('grub-script-check'), 'GRUB tools are unavailable')
    def test_label_command_checks_and_replaces_the_menu(self):
        closing = self.directory / 'closing.cfg'
        closing.write_text(CLOSING)
        check = shutil.which('grub-script-check')
        theme = self.directory / 'theme'
        theme.mkdir()
        (theme / 'startup-3.txt').write_text('')
        self.menu.write_text(generated(specialised=1), encoding='utf-8')
        label_menu(['--distro', 'NixOS', '--append', str(closing), '--theme', str(theme), '--check', check, str(self.menu)])
        labelled = self.menu.read_text(encoding='utf-8')
        self.assertEqual(labelled, label(generated(specialised=1), 'NixOS', CLOSING, {'startup-3'}.__contains__))
        self.assertIn('set theme=($drive1)//theme/startup-3.txt\n', labelled)
        theme.joinpath('startup-3.txt').unlink()
        theme.rmdir()
        broken = self.directory / 'broken.cfg'
        broken.write_text("menuentry 'Broken' {\n  if true; then\n}\n")
        self.menu.write_text(generated(), encoding='utf-8')
        with self.assertRaisesRegex(Failure, 'syntax check'):
            label_menu(['--distro', 'NixOS', '--append', str(broken), '--check', check, str(self.menu)])
        self.assertEqual(self.menu.read_text(encoding='utf-8'), generated())
        self.assertEqual(sorted(p.name for p in self.directory.iterdir()), ['broken.cfg', 'closing.cfg', 'grub.cfg'])


